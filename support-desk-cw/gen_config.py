#!/usr/bin/env python3
"""[HF-DESK-CW-1] hf-config.js for the agent desk, from Specs/brand.json (never type the brand or domain)."""
import base64, json, sys
b = json.load(open(sys.argv[1], encoding="utf-8"))
h = b["hosts"]
name = b.get("name") or b.get("nameCompact")
api = "https://" + h["api"] + "/cw"
key = "pk_live_" + base64.b64encode((h["auth"] + "$").encode()).decode()
cw = {
    "hostURL": "", "apiHost": api, "hfPoll": 5000,
    "enabledLanguages": [{"name": "English", "iso_639_1_code": "en"}], "selectedLocale": "en",
    "allowedLoginMethods": ["email"], "isEnterprise": "false", "signupEnabled": "false", "isMfaEnabled": "false",
}
gc = {
    "INSTALLATION_NAME": f"{name} Support", "BRAND_NAME": name, "LOGO": "", "LOGO_THUMBNAIL": "", "LOGO_DARK": "",
    "DEPLOYMENT_ENV": "self-hosted", "DISPLAY_MANIFEST": False, "LOGOUT_REDIRECT_LINK": "/app/login?signout=1",
    # [HF-DESK-THEME-1] our mark in the sidebar / account switcher, our wordmark where Chatwoot shows its logo
    "LOGO_THUMBNAIL": "/hf/hf-mark-128.png", "LOGO": "/hf/hf-wordmark.png", "LOGO_DARK": "/hf/hf-wordmark.png",
}
desk = {"name": name, "apiHost": api, "clerkHost": h["auth"], "clerkKey": key}
print("// generated by support-desk-cw/gen_config.py from Specs/brand.json - do not edit")
print(f"window.chatwootConfig={json.dumps(cw)};window.chatwootConfig.hostURL=location.origin;")
print(f"window.globalConfig={json.dumps(gc)};")
print("window.browserConfig={browser_name:'Chrome'};")
print(f"window.hfDesk={json.dumps(desk)};")
# [HF-DESK-THEME-1] fonts + theme. Added after the page's own stylesheets so they win; the dashboard only mounts on
# window.onload, so nothing is shown before they are in place.
print("""(function(){var add=function(){var h=document.head;
var p=document.createElement('link');p.rel='preconnect';p.href='https://fonts.gstatic.com';p.crossOrigin='anonymous';h.appendChild(p);
var f=document.createElement('link');f.rel='stylesheet';f.href='https://fonts.googleapis.com/css2?family=Comfortaa:wght@400;500;600;700&family=Nunito:wght@600;700;800;900&display=swap';h.appendChild(f);
var t=document.createElement('link');t.rel='stylesheet';t.href='/hf-theme.css';h.appendChild(t);};
if(document.readyState==='loading'){document.addEventListener('DOMContentLoaded',add);}else{add();}})();""")
# [HF-DESK-UX-1] The desk's designed look is the ivory (light) theme. Chatwoot follows the computer's dark mode by default
# ('auto'); start every agent on light once. Picking a theme later in Profile settings still sticks.
print("""(function(){try{if(!localStorage.getItem('hf_scheme_v1')){localStorage.setItem('color_scheme',JSON.stringify('light'));localStorage.setItem('hf_scheme_v1','1');}}catch(e){}})();""")
