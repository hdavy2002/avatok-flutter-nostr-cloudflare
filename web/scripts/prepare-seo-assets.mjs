/** Deterministic asset preparation. No network, AI calls or request-time font downloads. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const opentype = require('@shuding/opentype.js');
const web = fileURLToPath(new URL('../', import.meta.url));
const fontPath = join(web, 'public/fonts/Comfortaa-Bold.ttf');
const font = await readFile(fontPath);
const parsedFont = opentype.parse(font.buffer.slice(font.byteOffset, font.byteOffset + font.byteLength));
const source = await readFile(join(web, 'public/assets/saathum-grand/hero.png'));
const hero = await sharp(source).resize(900, 1000, { fit: 'cover' }).flatten({ background: '#f4dbad' }).jpeg({ quality: 82, chromaSubsampling: '4:4:4' }).toBuffer();

const background = Buffer.from('<svg width="1200" height="630" xmlns="http://www.w3.org/2000/svg"><rect width="1200" height="630" fill="#b94427"/><rect x="12" y="12" width="1176" height="606" fill="#fff8e8"/><rect x="720" y="56" width="424" height="518" rx="26" fill="#d39f53"/></svg>');
const art = await sharp(source).resize(416, 510, { fit: 'cover' }).png().toBuffer();
async function text(value, size, colour) {
  // Convert the bundled font's glyphs to paths: no system font/fontconfig differences in CI.
  const path = parsedFont.getPath(value, 0, size, size);
  path.fill = colour;
  const width = Math.ceil(parsedFont.getAdvanceWidth(value, size)) + 4;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${Math.ceil(size * 1.5)}"><path fill="${colour}" d="${path.toPathData(3)}"/></svg>`;
  return sharp(Buffer.from(svg)).png().toBuffer();
}
const fallback = await sharp(background).composite([
  { input: art, left: 724, top: 60 },
  { input: await text('Saathum', 48, '#ab3421'), left: 56, top: 64 },
  { input: await text('SACRED RITUALS, SHARED LIVE', 19, '#9b4b24'), left: 56, top: 164 },
  { input: await text('Sacred rituals.', 49, '#304d35'), left: 56, top: 237 },
  { input: await text('Shared live.', 49, '#304d35'), left: 56, top: 309 },
  { input: await text('Wherever you are.', 24, '#5a614d'), left: 56, top: 411 },
  { input: await text('saathum.com', 21, '#ab3421'), left: 56, top: 536 },
]).png({ palette: true, colours: 192, dither: 0, compressionLevel: 9 }).toBuffer();

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const generated = `// Generated by scripts/prepare-seo-assets.mjs; bundled for workerd (no filesystem/network).\n` +
  `export const fontRevision = ${JSON.stringify(hash(font))};\n` +
  `export const assetRevision = ${JSON.stringify(hash(Buffer.concat([hero, fallback])))};\n` +
  `export const fontBase64 = ${JSON.stringify(font.toString('base64'))};\n` +
  `export const heroDataUri = ${JSON.stringify('data:image/jpeg;base64,' + hero.toString('base64'))};\n` +
  `export const fallbackBase64 = ${JSON.stringify(fallback.toString('base64'))};\n`;
await mkdir(join(web, 'src/lib/seo/og'), { recursive: true });
await mkdir(join(web, 'public/seo'), { recursive: true });
await writeFile(join(web, 'src/lib/seo/og/assets.generated.ts'), generated);
await writeFile(join(web, 'public/seo/fallback.png'), fallback);
console.log(`Prepared SEO font (${font.length} bytes), hero (${hero.length} bytes), fallback (${fallback.length} bytes).`);
