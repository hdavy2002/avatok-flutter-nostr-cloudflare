#!/usr/bin/env python3
"""[HF-DESI-HOME-1] Regenerate the homepage body + stylesheet from the approved desi design file.

Source: web/design/desi-home.source.html (the page that was on hellofraands-desi.pages.dev).
Its own header/footer are dropped: the homepage uses the shared Header/Footer components so every
menu link is the real one. Placeholder '#...' links are rewired to real routes and in-page anchors.
Run from web/:  python3 scripts/build-desi-home.py
"""
import re, sys
from pathlib import Path

SRC = Path('design/desi-home.source.html')
OUT_BODY = Path('src/components/home/desi-home-body.html')
OUT_CSS = Path('src/styles/desi-home.css')
html = SRC.read_text()

css = re.search(r'<style>(.*?)</style>', html, re.S).group(1)
css = css.replace('/img/', '/assets/hf-desi/')
# The wrapper used overflow-x:hidden, which turns it into a scroll box and silently disables
# position:sticky on the header inside it. clip hides the sideways overflow without that side effect.
css = css.replace('.hf{', '.hf{overflow-x:clip;').replace(';overflow-x:hidden}', '}')
css = re.sub(r'^body\{[^}]*\}\n', '', css, flags=re.M)
# Background art goes through the public image pipeline: index.astro defines --dh-<name> with publicImage().
css = re.sub(r'url\(/assets/hf-desi/([a-z0-9-]+)\.webp\)', lambda m: f'var(--dh-{m.group(1)})', css)

start = html.index('<!-- ===== TORAN')
end = html.index('<!-- ===== FOOTER')
body = html[start:end].replace('/img/', '/assets/hf-desi/')

def sub1(old, new):
    global body
    if old not in body:
        sys.exit(f'build-desi-home: pattern not found: {old!r}')
    body = body.replace(old, new, 1)

# In-page anchors the shared header/footer link to (/#people, /#naye-dost, /#moods, /#how-it-works).
sub1('href="#explore" class="btn btn-dark">Find your people', 'href="#people" class="btn btn-dark" data-home-cta="find-people">Find your people')
sub1('<a href="#how" class="btn btn-light">', '<a href="#how-it-works" class="btn btn-light" data-home-cta="how-it-works">')
sub1('<section id="how" ', '<section id="how-it-works" data-home-section="how-it-works" ')
sub1('<section id="explore" class="wrap creators-sec" style="padding: 88px 0 96px">', '<section id="people" data-home-section="creators" class="wrap creators-sec" style="padding: 88px 0 96px"><span id="naye-dost" class="dh-anchor"></span>')
sub1('<!-- ===== REASONS (Warli icons, block-print cards) ===== -->\n<section style="position: relative">', '<!-- ===== REASONS (Warli icons, block-print cards) ===== -->\n<section id="moods" data-home-section="reasons" style="position: relative">')
sub1('<!-- ===== PRIVACY (elephant) ===== -->\n<section style="position: relative; overflow: hidden">', '<!-- ===== PRIVACY (elephant) ===== -->\n<section id="safety" data-home-section="privacy" style="position: relative; overflow: hidden">')
sub1('<section id="top" class="hero wrap"', '<section id="top" data-home-section="hero" class="hero wrap"')
sub1('<section id="download" ', '<section id="download" data-home-section="download" ')

# Everything that pointed at the creators grid or a profile goes to the real Explore page.
body = re.sub(r'href="#(?:explore|meera|kabir|ananya|rohan)"', 'href="/marketplace" data-home-cta="explore"', body)
body = body.replace('href="#play"', 'href="__HF_PLAY_URL__" data-home-cta="google-play" rel="noopener"')
# No App Store listing exists yet: a truthful, non-link "Coming soon" state.
lines = []
for line in body.split('\n'):
    if 'href="#ios"' in line:
        line = line.replace('<a href="#ios"', '<span aria-disabled="true" title="Coming soon"', 1)
        i = line.rfind('</a>')
        line = line[:i] + '</span>' + line[i + 4:]
    lines.append(line)
body = '\n'.join(lines)

# Brand name comes from Specs/brand.json at render time (CLAUDE.md brand rule).
body = body.replace('Hello Fraands', '__BRAND_NAME__')

left = re.findall(r'href="#[^"]*"', body)
allowed = {'href="#people"', 'href="#how-it-works"'}
if set(left) - allowed:
    sys.exit(f'build-desi-home: unmapped placeholder links: {sorted(set(left) - allowed)}')

body = ('<!-- GENERATED by web/scripts/build-desi-home.py from web/design/desi-home.source.html. '
        'Edit the design file and re-run; do not hand-edit. -->\n<main id="main-content">\n' + body.strip() +
        '\n</main>\n<div class="toran dh-footer-toran" aria-hidden="true"></div>\n')
OUT_BODY.write_text(body)
OUT_CSS.write_text('/* GENERATED by web/scripts/build-desi-home.py from the desi design file — do not hand-edit. */\n'
                   + css.strip() + '\n')
print(f'wrote {OUT_BODY} ({len(body)} bytes) and {OUT_CSS} ({len(css)} bytes)')
